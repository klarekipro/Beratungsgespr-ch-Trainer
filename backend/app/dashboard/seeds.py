def _summary(scenario, phase):
    values = [f["value"] for f in scenario["facts"]
              if f["stage"] == phase and f["required"] and f["status"] != "not_applicable"]
    return "Правильно ли я понял: " + " ".join(values)


def _walkthrough(scenario, need_questions, capability_questions, proposal):
    return {
        "scenario_id": scenario["id"],
        "turns": (
            [{"text": text, "kind": "message"} for text in need_questions]
            + [{"text": _summary(scenario, "needs"), "kind": "summary"}]
            + [{"text": text, "kind": "message"} for text in capability_questions]
            + [{"text": _summary(scenario, "capabilities"), "kind": "summary"}]
            + [{"text": proposal, "kind": "proposal"}]
        ),
    }


